-- DBTITLE 1,Create dim_date
CREATE TABLE IF NOT EXISTS dim_date (
  date_key         INT     NOT NULL COMMENT 'Surrogate key in yyyyMMdd form (e.g. 20250131); -1 = unknown date.',
  full_date        DATE    NOT NULL COMMENT 'Calendar date (business key).',
  day_of_month     INT     NOT NULL COMMENT 'Day number in month (1-31).',
  day_name         STRING  NOT NULL COMMENT 'Monday ... Sunday.',
  iso_day_of_week  INT     NOT NULL COMMENT 'ISO day of week: 1 = Monday ... 7 = Sunday.',
  is_weekend       BOOLEAN NOT NULL COMMENT 'TRUE on Saturday and Sunday.',
  day_type         STRING  NOT NULL COMMENT 'Weekday | Weekend.',
  iso_week         INT     NOT NULL COMMENT 'ISO week number.',
  month_num        INT     NOT NULL COMMENT 'Month number (1-12).',
  month_name       STRING  NOT NULL COMMENT 'January ... December.',
  month_short      STRING  NOT NULL COMMENT 'Jan ... Dec.',
  year_month       STRING  NOT NULL COMMENT 'yyyy-MM, e.g. 2025-01.',
  month_start_date DATE    NOT NULL COMMENT 'First day of the month (handy for time-series charts).',
  quarter_num      INT     NOT NULL COMMENT 'Calendar quarter (1-4).',
  year_quarter     STRING  NOT NULL COMMENT 'yyyy-Qn, e.g. 2025-Q1.',
  year_num         INT     NOT NULL COMMENT 'Calendar year.',
  CONSTRAINT pk_dim_date PRIMARY KEY (date_key)
)
COMMENT 'GOLD: calendar dimension 2024-01-01 to 2025-12-31 plus unknown member (-1).';

-- COMMAND ----------

-- DBTITLE 1,Load dim_date (deterministic -> INSERT OVERWRITE is idempotent)
-- date_key is derived from the date itself, so a full rebuild never changes a key.
INSERT OVERWRITE dim_date
SELECT
  CAST(date_format(d, 'yyyyMMdd') AS INT)        AS date_key,
  d                                              AS full_date,
  dayofmonth(d)                                  AS day_of_month,
  date_format(d, 'EEEE')                         AS day_name,
  weekday(d) + 1                                 AS iso_day_of_week,
  weekday(d) >= 5                                AS is_weekend,
  CASE WHEN weekday(d) >= 5 THEN 'Weekend' ELSE 'Weekday' END AS day_type,
  weekofyear(d)                                  AS iso_week,
  month(d)                                       AS month_num,
  date_format(d, 'MMMM')                         AS month_name,
  date_format(d, 'MMM')                          AS month_short,
  date_format(d, 'yyyy-MM')                      AS year_month,
  trunc(d, 'MM')                                 AS month_start_date,
  quarter(d)                                     AS quarter_num,
  concat(year(d), '-Q', quarter(d))              AS year_quarter,
  year(d)                                        AS year_num
FROM (SELECT explode(sequence(DATE'2024-01-01', DATE'2025-12-31', INTERVAL 1 DAY)) AS d)
UNION ALL
SELECT -1, DATE'1900-01-01', 0, 'Unknown', 0, false, 'Unknown', 0, 0, 'Unknown', 'Unk',
       'Unknown', DATE'1900-01-01', 0, 'Unknown', 0;

