-- DBTITLE 1,Create dim_customer
CREATE TABLE IF NOT EXISTS dim_customer (
  customer_key  BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1)
                COMMENT 'Surrogate key; -1 = Guest / Unknown customer.',
  customer_id   STRING NOT NULL COMMENT 'Business key from the source system (C0001...).',
  first_name    STRING COMMENT 'First name.',
  last_name     STRING COMMENT 'Last name.',
  full_name     STRING COMMENT 'First + last name.',
  email         STRING COMMENT 'E-mail (NULL when missing in source).',
  gender        STRING COMMENT 'M | F.',
  birth_date    DATE   COMMENT 'Date of birth.',
  age_band      STRING COMMENT 'Age band at load time (18-29, 30-39, ...).',
  city          STRING COMMENT 'Current city.',
  region        STRING COMMENT 'Current region.',
  segment       STRING COMMENT 'Current segment: Retail | Loyalty Silver | Loyalty Gold (Guest for -1).',
  signup_date   DATE   COMMENT 'Signup date.',
  _attr_hash    STRING NOT NULL COMMENT 'SHA-256 of the SCD1 attributes; drives change detection.',
  _inserted_at  TIMESTAMP NOT NULL COMMENT 'When the row was first inserted.',
  _updated_at   TIMESTAMP NOT NULL COMMENT 'When the row was last changed.',
  CONSTRAINT pk_dim_customer PRIMARY KEY (customer_key)
)
COMMENT 'GOLD: customer dimension, SCD Type 1 (current attributes). -1 = Guest / Unknown.'
TBLPROPERTIES (delta.enableChangeDataFeed = true);

-- COMMAND ----------

-- DBTITLE 1,Unknown member (-1)
MERGE INTO dim_customer AS t
USING (SELECT CAST(-1 AS BIGINT) AS customer_key) AS s
ON t.customer_key = s.customer_key
WHEN NOT MATCHED THEN INSERT
  (customer_key, customer_id, first_name, last_name, full_name, email, gender, birth_date, age_band,
   city, region, segment, signup_date, _attr_hash, _inserted_at, _updated_at)
VALUES
  (-1, 'N/A', 'Guest', 'Customer', 'Guest / Unknown', NULL, NULL, NULL, 'Unknown',
   'Unknown', 'Unknown', 'Guest', NULL, sha2('unknown', 256), current_timestamp(), current_timestamp());

-- COMMAND ----------

-- DBTITLE 1,Load dim_customer (MERGE, SCD1)
MERGE INTO dim_customer AS t
USING (
  WITH latest_change AS (
    SELECT customer_id, new_city, new_region, new_segment
    FROM (
      SELECT *, row_number() OVER (PARTITION BY customer_id ORDER BY effective_date DESC) AS rn
      FROM IDENTIFIER(:silver_schema || '.customer_changes')
      WHERE effective_date <= current_date()
    )
    WHERE rn = 1
  ),
  src AS (
    SELECT
      c.customer_id,
      c.first_name,
      c.last_name,
      concat_ws(' ', c.first_name, c.last_name)                AS full_name,
      c.email,
      c.gender,
      c.birth_date,
      CASE
        WHEN c.birth_date IS NULL                                       THEN 'Unknown'
        WHEN floor(months_between(current_date(), c.birth_date) / 12) < 30 THEN '18-29'
        WHEN floor(months_between(current_date(), c.birth_date) / 12) < 40 THEN '30-39'
        WHEN floor(months_between(current_date(), c.birth_date) / 12) < 50 THEN '40-49'
        WHEN floor(months_between(current_date(), c.birth_date) / 12) < 60 THEN '50-59'
        ELSE '60+'
      END                                                      AS age_band,
      coalesce(lc.new_city,    c.city)                         AS city,
      coalesce(lc.new_region,  c.region)                       AS region,
      coalesce(lc.new_segment, c.segment)                      AS segment,
      c.signup_date
    FROM IDENTIFIER(:silver_schema || '.customers') AS c
    LEFT JOIN latest_change AS lc ON lc.customer_id = c.customer_id
  )
  SELECT *,
         sha2(to_json(struct(first_name, last_name, email, gender, birth_date, age_band,
                             city, region, segment, signup_date)), 256) AS _attr_hash
  FROM src
) AS s
ON t.customer_id = s.customer_id
WHEN MATCHED AND t._attr_hash <> s._attr_hash THEN UPDATE SET
  t.first_name  = s.first_name,
  t.last_name   = s.last_name,
  t.full_name   = s.full_name,
  t.email       = s.email,
  t.gender      = s.gender,
  t.birth_date  = s.birth_date,
  t.age_band    = s.age_band,
  t.city        = s.city,
  t.region      = s.region,
  t.segment     = s.segment,
  t.signup_date = s.signup_date,
  t._attr_hash  = s._attr_hash,
  t._updated_at = current_timestamp()
WHEN NOT MATCHED THEN INSERT
  (customer_id, first_name, last_name, full_name, email, gender, birth_date, age_band,
   city, region, segment, signup_date, _attr_hash, _inserted_at, _updated_at)
VALUES
  (s.customer_id, s.first_name, s.last_name, s.full_name, s.email, s.gender, s.birth_date, s.age_band,
   s.city, s.region, s.segment, s.signup_date, s._attr_hash, current_timestamp(), current_timestamp());

