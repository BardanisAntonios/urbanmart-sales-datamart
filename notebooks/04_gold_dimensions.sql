-- MAGIC %md
-- MAGIC ## 3. `dim_customer_scd2` — SCD Type 2 (stretch goal)
-- MAGIC Tracked attributes: **city, region, segment**.
-- MAGIC - Version 1 of every customer = the master record, valid from `1900-01-01` (the extract has no older history, and orders can predate `signup_date`).
-- MAGIC - Every row of `customer_changes` opens a new version on its `effective_date`; the previous version is closed the day before.
-- MAGIC - Open versions have `valid_to = 9999-12-31` and `is_current = true`.
-- MAGIC
-- MAGIC The version set is recomputed from silver on every run and **merged on (`customer_id`, `valid_from`)**, so
-- MAGIC existing versions keep their surrogate key, new versions are inserted and closed versions get their `valid_to` updated.
-- MAGIC Re-running inserts nothing.

-- COMMAND ----------

-- DBTITLE 1,Create dim_customer_scd2
CREATE TABLE IF NOT EXISTS dim_customer_scd2 (
  customer_version_key BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1)
                       COMMENT 'Surrogate key of the customer version; -1 = Guest / Unknown.',
  customer_id          STRING  NOT NULL COMMENT 'Business key.',
  full_name            STRING  COMMENT 'First + last name (not tracked).',
  city                 STRING  COMMENT 'City in this version (tracked).',
  region               STRING  COMMENT 'Region in this version (tracked).',
  segment              STRING  COMMENT 'Segment in this version (tracked).',
  valid_from           DATE    NOT NULL COMMENT 'First day the version is valid.',
  valid_to             DATE    NOT NULL COMMENT 'Last day the version is valid; 9999-12-31 while open.',
  is_current           BOOLEAN NOT NULL COMMENT 'TRUE for the open version.',
  version_num          INT     NOT NULL COMMENT '1, 2, ... per customer.',
  change_source        STRING  NOT NULL COMMENT 'INITIAL_LOAD | CUSTOMER_CHANGES | SEED.',
  _inserted_at         TIMESTAMP NOT NULL COMMENT 'When the version was inserted.',
  _updated_at          TIMESTAMP NOT NULL COMMENT 'When the version was last changed (e.g. closed).',
  CONSTRAINT pk_dim_customer_scd2 PRIMARY KEY (customer_version_key)
)
COMMENT 'GOLD: customer dimension, SCD Type 2 on city / region / segment. Use for point-in-time analysis.'
TBLPROPERTIES (delta.enableChangeDataFeed = true);

-- COMMAND ----------

-- DBTITLE 1,CHECK constraint (enforced): a version cannot end before it starts
ALTER TABLE dim_customer_scd2 DROP CONSTRAINT IF EXISTS ck_scd2_valid_range;
ALTER TABLE dim_customer_scd2 ADD  CONSTRAINT ck_scd2_valid_range CHECK (valid_to >= valid_from);

-- COMMAND ----------

-- DBTITLE 1,Unknown member (-1)
MERGE INTO dim_customer_scd2 AS t
USING (SELECT CAST(-1 AS BIGINT) AS customer_version_key) AS s
ON t.customer_version_key = s.customer_version_key
WHEN NOT MATCHED THEN INSERT
  (customer_version_key, customer_id, full_name, city, region, segment, valid_from, valid_to,
   is_current, version_num, change_source, _inserted_at, _updated_at)
VALUES
  (-1, 'N/A', 'Guest / Unknown', 'Unknown', 'Unknown', 'Guest', DATE'1900-01-01', DATE'9999-12-31',
   true, 1, 'SEED', current_timestamp(), current_timestamp());

-- COMMAND ----------

-- DBTITLE 1,Load dim_customer_scd2 (MERGE on customer_id + valid_from)
MERGE INTO dim_customer_scd2 AS t
USING (
  WITH events AS (
    SELECT customer_id, city, region, segment,
           DATE'1900-01-01' AS valid_from, 'INITIAL_LOAD' AS change_source
    FROM IDENTIFIER(:silver_schema || '.customers')
    UNION ALL
    SELECT customer_id, new_city, new_region, new_segment,
           effective_date, 'CUSTOMER_CHANGES'
    FROM IDENTIFIER(:silver_schema || '.customer_changes')
  ),
  versions AS (
    SELECT e.*,
           coalesce(date_sub(lead(valid_from) OVER (PARTITION BY customer_id ORDER BY valid_from), 1),
                    DATE'9999-12-31')                                              AS valid_to,
           row_number() OVER (PARTITION BY customer_id ORDER BY valid_from)        AS version_num
    FROM events e
  )
  SELECT v.customer_id,
         concat_ws(' ', c.first_name, c.last_name) AS full_name,
         v.city, v.region, v.segment,
         v.valid_from, v.valid_to,
         v.valid_to = DATE'9999-12-31'             AS is_current,
         CAST(v.version_num AS INT)                AS version_num,
         v.change_source
  FROM versions v
  JOIN IDENTIFIER(:silver_schema || '.customers') AS c ON c.customer_id = v.customer_id
) AS s
ON t.customer_id = s.customer_id AND t.valid_from = s.valid_from
WHEN MATCHED AND (   t.valid_to    <> s.valid_to
                  OR t.is_current  <> s.is_current
                  OR t.version_num <> s.version_num
                  OR NOT (t.city    <=> s.city)
                  OR NOT (t.region  <=> s.region)
                  OR NOT (t.segment <=> s.segment)
                  OR NOT (t.full_name <=> s.full_name)) THEN UPDATE SET
  t.full_name   = s.full_name,
  t.city        = s.city,
  t.region      = s.region,
  t.segment     = s.segment,
  t.valid_to    = s.valid_to,
  t.is_current  = s.is_current,
  t.version_num = s.version_num,
  t._updated_at = current_timestamp()
WHEN NOT MATCHED THEN INSERT
  (customer_id, full_name, city, region, segment, valid_from, valid_to, is_current,
   version_num, change_source, _inserted_at, _updated_at)
VALUES
  (s.customer_id, s.full_name, s.city, s.region, s.segment, s.valid_from, s.valid_to, s.is_current,
   s.version_num, s.change_source, current_timestamp(), current_timestamp());

-- COMMAND ----------

-- DBTITLE 1,Example: one customer with history
SELECT customer_version_key, customer_id, city, region, segment, valid_from, valid_to, is_current, version_num
FROM dim_customer_scd2
WHERE customer_id IN (SELECT customer_id FROM dim_customer_scd2 WHERE version_num = 2 LIMIT 1)
ORDER BY valid_from;

