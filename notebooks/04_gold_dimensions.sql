-- MAGIC %md
-- MAGIC # 04 · Gold — Dimensions
-- MAGIC
-- MAGIC | Dimension | Business key | Type | Unknown member |
-- MAGIC |---|---|---|---|
-- MAGIC | `dim_date` | `full_date` (key `date_key` = yyyyMMdd) | Static calendar 2024-01-01 → 2025-12-31 | `-1` |
-- MAGIC | `dim_customer` | `customer_id` | SCD Type 1 (current state, latest change applied) | `-1` = Guest / Unknown |
-- MAGIC | `dim_customer_scd2` | `customer_id` + `valid_from` | **SCD Type 2** (stretch) — city / region / segment history | `-1` |
-- MAGIC | `dim_product` | `product_id` | SCD Type 1 | `-1` = Unknown product |
-- MAGIC | `dim_store` | `store_id` | SCD Type 1 | `-1` = Unknown store |
-- MAGIC | `dim_order_profile` | `payment_method` + `order_status` | **Junk dimension** (stretch) | `-1` |
-- MAGIC
-- MAGIC **Design choices**
-- MAGIC - Surrogate keys: `BIGINT GENERATED BY DEFAULT AS IDENTITY`. *BY DEFAULT* (not *ALWAYS*) lets us insert the unknown member with key `-1` explicitly.
-- MAGIC - Tables are created once (`CREATE TABLE IF NOT EXISTS`) and loaded with **`MERGE INTO`** on the business key.
-- MAGIC   This keeps surrogate keys **stable across re-runs** (a `CREATE OR REPLACE` would re-number them) and makes the notebook idempotent:
-- MAGIC   a second run updates nothing and inserts nothing.
-- MAGIC - A hash of the descriptive attributes (`_attr_hash`) detects real changes, so unchanged rows are not rewritten.
-- MAGIC - `PRIMARY KEY` constraints are **informational** in Unity Catalog (not enforced) → uniqueness is tested in notebook 06.
-- MAGIC   `CHECK` constraints **are** enforced by Delta.

